"""Run every analysis on a round's raw data and write the results table for the round report.

Looks at each file in the folder (and in sub-folders, one per reducer or set-up, e.g. P0/A and P0/B) and decides
what it is from its content, not its name:
  .txt console logs: "i,arcsec" -> encoder_noise; "t_s,cmd_deg,enc_deg,dev_arcsec" -> encoder_sweep;
                     "t_s,cmd_arcsec,..." -> periodic_error; "pass,n,dir,..." -> lost_motion; "t_s,set_dps,..." -> slew_stallguard
  .json replies:     cal.status -> encoder map; pec.get -> PEC table
  .csv:              "t_s,arcsec" (laser_spot.py) -> periodic_error; bench-logger head recordings -> temperatures (and
                     periodic_error --pec when the name contains "pec"); "mode,volts,amps" -> power; "pass,n,dial_um" -> dial
Writes results.md and results.json in each folder. Every number links back to its raw file.

Usage: python tools/measure/report.py docs/measurements/P0
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import stlog
import encoder_noise
import encoder_sweep
import periodic_error
import lost_motion
import slew_stallguard
import head_results
import power


def classify(p: Path) -> str | None:
    suf = p.suffix.lower()
    try:
        if suf == ".txt" or suf == ".log":
            heads = [b["header"][:4] for b in stlog.csv_blocks(stlog.read_text(p))]
            for h in reversed(heads):
                if h[:2] == ["i", "arcsec"]:
                    return "noise"
                if h[:4] == ["t_s", "cmd_deg", "enc_deg", "dev_arcsec"]:
                    return "sweep"
                if h[:2] == ["t_s", "cmd_arcsec"]:
                    return "track"
                if h[:3] == ["pass", "n", "dir"]:
                    return "lost"
                if h[:2] == ["t_s", "set_dps"]:
                    return "slew"
            return None
        if suf == ".json":
            j = stlog.read_json(p)
            r = j.get("result", j) if isinstance(j, dict) else {}
            if isinstance(r, dict) and ("routine" in r or "after_rms_as" in r.get("result", {})):
                return "cal"
            if isinstance(r, dict) and "table_as" in r:
                return "pec"
            return None
        if suf == ".csv":
            first = stlog.read_text(p).splitlines()[0].lower()
            if first.startswith("t_s,arcsec"):
                return "laser"
            if first.startswith("mode,volts,amps"):
                return "power"
            if first.startswith("pass,n,dial_um"):
                return "dial"
            if "az_enc_d" in first:
                return "head_pec" if "pec" in p.name.lower() else "head"
    except Exception:
        return None
    return None


def run_folder(folder: Path) -> list[stlog.Result]:
    files = sorted([p for p in folder.iterdir() if p.is_file() and not p.name.startswith("results")])
    kinds: dict[str, list[Path]] = {}
    for p in files:
        k = classify(p)
        if k:
            kinds.setdefault(k, []).append(p)
    res: list[stlog.Result] = []
    an = folder / "analysis"
    pe_json = None
    for p in kinds.get("noise", []):
        res += encoder_noise.analyse(p, an / p.stem)["results"]
    for p in kinds.get("sweep", []):
        res += encoder_sweep.analyse(p, an / p.stem)["results"]
    for p in kinds.get("track", []) + kinds.get("laser", []):
        s = periodic_error.analyse(p, "az", False, an / p.stem)
        res += s["results"]
        if s["duration_s"] >= 2 * stlog.WG_PERIOD_S:
            pe_json = an / p.stem / "periodic_error.json"
    dial = kinds.get("dial", [None])[0]
    for p in kinds.get("lost", []):
        res += lost_motion.analyse(p, "az", dial, 200.0, an / p.stem)["results"]
    if kinds.get("slew"):
        res += slew_stallguard.analyse(kinds["slew"], an / "slew")["results"]

    class A:
        pass
    for p in kinds.get("cal", []) + kinds.get("pec", []):
        a = A()
        a.cal = p if p in kinds.get("cal", []) else None
        a.pec = p if p in kinds.get("pec", []) else None
        a.pe, a.head, a.axis, a.out = pe_json, None, "az", an / p.stem
        res += head_results.main(a)["results"]
    for p in kinds.get("head", []):
        a = A()
        a.cal = a.pec = a.pe = None
        a.head, a.axis, a.out = p, "az", an / p.stem
        res += head_results.main(a)["results"]
    for p in kinds.get("head_pec", []):
        res += periodic_error.analyse(p, "az", True, an / p.stem)["results"]
        a = A()
        a.cal = a.pec = a.pe = None
        a.head, a.axis, a.out = p, "az", an / (p.stem + "_temps")
        res += head_results.main(a)["results"]
    for p in kinds.get("power", []):
        res += power.analyse(p, None, None, out=an / p.stem)["results"]
    lines = [f"# Results — {folder.as_posix()}", "",
             "Generated by `tools/measure/report.py` from the raw files in this folder. Limits and their sources are in `tools/measure/stlog.py`.", "",
             "| Test | Quantity | Measured | Limit | Verdict | Raw file | Note |", "|---|---|---|---|---|---|---|"]
    for r in res:
        lines.append("| " + " | ".join(x.replace("|", "/") for x in r.row()) + " |")
    if not res:
        lines.append("| — | no raw data yet | | | not run | | |")
    unknown = [p.name for p in files if not classify(p) and p.suffix.lower() in (".txt", ".csv", ".json", ".log")]
    if unknown:
        lines += ["", "Files not recognised: " + ", ".join(unknown)]
    (folder / "results.md").write_text("\n".join(lines) + "\n")
    stlog.write_json(folder / "results.json", {"results": res})
    return res


def main(root: Path) -> None:
    folders = [root] + sorted([d for d in root.iterdir() if d.is_dir() and d.name != "analysis"])
    for f in folders:
        if any(classify(p) for p in f.iterdir() if p.is_file()):
            res = run_folder(f)
            print(f"{f}: {len(res)} results -> {f / 'results.md'}")


if __name__ == "__main__":
    a = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    a.add_argument("folder", type=Path)
    main(a.parse_args().folder)
