#!/usr/bin/env python3
"""Generate app/shared/catalog_data.js: named bright stars (PyEphem's star list, J2000), the Messier objects and NGC/IC
objects brighter than V 10 (OpenNGC through PyOngc). Run again to refresh; the output is committed so the apps need
neither package."""
import json
import pathlib

import ephem
import ephem.stars
from pyongc import ongc

OUT = pathlib.Path(__file__).resolve().parents[1] / "shared/catalog_data.js"


def hms(c):
    return c[0] + c[1] / 60 + c[2] / 3600


def main():
    stars = []
    for line in ephem.stars.db.strip().splitlines():
        name = line.split(",")[0]
        s = ephem.star(name)
        s.compute("2000/1/1.5", epoch="2000")
        stars.append({"n": name, "t": "star", "ra": round(float(s.a_ra) * 12 / ephem.pi, 5), "dec": round(float(s.a_dec) * 180 / ephem.pi, 4),
                      "m": round(float(s.mag), 2)})
    dso, seen = [], set()
    TYPES = {"Galaxy": "galaxy", "Open Cluster": "open cluster", "Globular Cluster": "globular", "Planetary Nebula": "planetary",
             "Emission Nebula": "nebula", "Reflection Nebula": "nebula", "HII Ionized region": "nebula", "Nebula": "nebula",
             "Supernova remnant": "supernova remnant", "Cluster + Nebula": "cluster + nebula", "Star cluster + Nebula": "cluster + nebula",
             "Association of stars": "asterism", "Double star": "double star", "Group of galaxies": "galaxy group", "Galaxy Pair": "galaxy pair"}

    def add(o, label):
        if o.name in seen or o.coords is None:
            return
        seen.add(o.name)
        ra, dec = hms(o.coords[0]), o.coords[1]
        d = abs(dec[0]) + dec[1] / 60 + dec[2] / 3600
        sign = -1 if str(o.dec).startswith("-") else 1
        mags = o.magnitudes
        m = mags[1] if mags[1] is not None else mags[0]
        common = (o.identifiers[3] or [None])[0] if o.identifiers and o.identifiers[3] else None
        e = {"n": label, "t": TYPES.get(o.type, o.type.lower()), "ra": round(ra, 5), "dec": round(sign * d, 4)}
        if m is not None:
            e["m"] = round(m, 1)
        if common:
            e["c"] = common
        if label.startswith("M") and o.name.startswith(("NGC", "IC")):
            e["x"] = o.name.replace("NGC0", "NGC ").replace("NGC00", "NGC ").replace("IC0", "IC ").replace("NGC", "NGC ").replace("  ", " ")
        if o.dimensions and o.dimensions[0]:
            e["s"] = round(o.dimensions[0], 1)    # major axis, arcmin
        dso.append(e)

    for i in range(1, 111):
        try:
            add(ongc.Dso(f"M{i}"), f"M{i}")
        except Exception as ex:  # noqa: BLE001
            print("skip", i, ex)
    for o in ongc.listObjects(uptovmag=10.0):
        if o.name.startswith(("NGC", "IC")):
            label = o.name.replace("NGC", "NGC ").replace("IC", "IC ")
            label = label.split(" ")[0] + " " + label.split(" ")[1].lstrip("0")
            add(o, label)
    js = ("// GENERATED by app/tools/make_catalog.py: named stars (PyEphem, J2000), Messier and NGC/IC brighter than V 10\n"
          "// (OpenNGC via PyOngc). n name, t type, ra hours J2000, dec degrees J2000, m magnitude, c common name, s size arcmin.\n"
          f"export const STARS = {json.dumps(stars, separators=(',', ':'))};\n"
          f"export const DSO = {json.dumps(dso, separators=(',', ':'), ensure_ascii=False)};\n")
    OUT.write_text(js)
    print(f"{len(stars)} stars, {len(dso)} deep-sky objects -> {OUT} ({len(js) // 1024} KB)")


if __name__ == "__main__":
    main()
