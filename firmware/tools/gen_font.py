#!/usr/bin/env python3
"""Render a 6x8 bitmap font (ASCII 32-126) for the SH1106 OLED from Liberation Mono into font6x8.h.
Each glyph = 6 column bytes, bit 0 = top row (SH1106 page format)."""
import pathlib
from PIL import Image, ImageDraw, ImageFont

FONT = "/usr/share/fonts/truetype/liberation/LiberationMono-Regular.ttf"
OUT = pathlib.Path(__file__).resolve().parents[1] / "esp32s3/components/st_hal/font6x8.h"
f = ImageFont.truetype(FONT, 9)
rows = []
for code in range(32, 127):
    img = Image.new("L", (6, 8), 0)
    d = ImageDraw.Draw(img)
    d.text((0, -1), chr(code), font=f, fill=255)
    cols = []
    for x in range(6):
        b = 0
        for y in range(8):
            if img.getpixel((x, y)) > 110:
                b |= 1 << y
        cols.append(b)
    rows.append("  {" + ", ".join(f"0x{c:02X}" for c in cols) + f"}},  /* '{chr(code) if code != 92 else 'backslash'}' */")
OUT.write_text("/* GENERATED by firmware/tools/gen_font.py (Liberation Mono 9 px, threshold 110). 6x8, ASCII 32..126 */\n#pragma once\n#include <stdint.h>\n"
               "static const uint8_t FONT6X8[95][6] = {\n" + "\n".join(rows) + "\n};\n")
print("wrote", OUT)
